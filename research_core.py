def build_research_question_prompt(topic):
    """
    研究テーマを研究可能な問いへ整理するための
    Research Runner用プロンプトを作成する。

    この段階ではWeb Search / File Searchは行わない。
    """

    clean_topic = str(topic).strip()

    if not clean_topic:
        raise ValueError(
            "研究テーマが入力されていません。"
        )

    return f"""
あなたは「EGAI-OT Research Runner」です。

以下の研究テーマについて、
現時点で与えられている情報だけを用いて、
研究可能な問いへ整理してください。

この段階では外部検索を行わず、
入力されていない事実を推測で補わないでください。

【研究テーマ】
{clean_topic}

以下の項目で整理してください。

1. 研究テーマ
2. 背景として確認する必要があること
3. 研究上の問題
4. 研究疑問の候補
5. 適しそうな研究疑問の形式
   （PICO、PECO、PEO、SPIDER等。無理に当てはめない）
6. 検索に使用するとよいキーワード
7. 現時点で分からないこと
8. 次の文献検索で確認すべき問い

重要：
・まだ先行研究を確認していないため、
  新規性や独自性があると断定しないでください。
・確認できていない内容は
  「未確認」と明示してください。
・個人を特定できる情報は求めないでください。
""".strip()

# =========================================================
# Research Search Prompt
# =========================================================


def build_research_search_prompt(topic, question_summary=None):
    """
    研究テーマについて、
    先行研究を検索・整理するためのプロンプトを作成する。
    """

    clean_topic = str(topic).strip()

    if not clean_topic:
        raise ValueError(
            "研究テーマが入力されていません。"
        )

    summary_text = ""

    if question_summary:
        summary_text = (
            "\n\n【事前に整理した研究疑問】\n"
            f"{str(question_summary).strip()}"
        )

    return f"""
あなたは「EGAI-OT Research Runner」です。

以下の研究テーマについて、
先行研究を確認するための検索と整理を行ってください。

【研究テーマ】
{clean_topic}
{summary_text}

以下の観点で確認してください。

1. 主要な先行研究
2. 現在までに分かっていること
3. 研究結果が一致している点
4. 研究結果が一致していない点
5. まだ十分に分かっていないこと
6. 研究対象・方法・評価指標の傾向
7. 今後さらに確認すべき検索語
8. 研究ギャップ候補

重要：
・検索で確認できた情報と、
  AIによる解釈を区別してください。
・新規性や独自性は、
  十分な先行研究確認なしに断定しないでください。
・研究ギャップは
  「候補」として示してください。
・一次資料、学術論文、公的機関、
  専門学会など信頼性の高い情報を優先してください。
・個人を特定できる情報は求めないでください。
""".strip()