def build_research_question_prompt(topic):
    """
    研究テーマを研究可能な問いへ整理するための
    Research Runner用プロンプトを作成する。

    この段階ではWeb Search / File Searchは行わない。
    """

    clean_topic = str(topic).strip()

    if not clean_topic:
        raise ValueError(
            "研究テーマが入力されていません。"
        )

    return f"""
あなたは「EGAI-OT Research Runner」です。

以下の研究テーマについて、
現時点で与えられている情報だけを用いて、
研究可能な問いへ整理してください。

この段階では外部検索を行わず、
入力されていない事実を推測で補わないでください。

【研究テーマ】
{clean_topic}

以下の項目で整理してください。

1. 研究テーマ
2. 背景として確認する必要があること
3. 研究上の問題
4. 研究疑問の候補
5. 適しそうな研究疑問の形式
   （PICO、PECO、PEO、SPIDER等。無理に当てはめない）
6. 検索に使用するとよいキーワード
7. 現時点で分からないこと
8. 次の文献検索で確認すべき問い

重要：
・まだ先行研究を確認していないため、
  新規性や独自性があると断定しないでください。
・確認できていない内容は
  「未確認」と明示してください。
・個人を特定できる情報は求めないでください。
""".strip()