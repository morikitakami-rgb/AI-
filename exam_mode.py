# 苦手分析
# =========================================================

def create_empty_exam_stats():
    """
    国家試験学習用の初期成績データを作成する。
    """

    return {
        "total_questions": 0,
        "correct_answers": 0,
        "by_category": defaultdict(
            lambda: {
                "total": 0,
                "correct": 0,
            }
        ),
        "wrong_topics": [],
    }


def record_answer(
    stats,
    category,
    topic,
    is_correct,
):
    """
    1問の結果を学習履歴に追加する。
    """

    stats["total_questions"] += 1

    stats["by_category"][category][
        "total"
    ] += 1

    if is_correct:

        stats["correct_answers"] += 1

        stats["by_category"][category][
            "correct"
        ] += 1

    else:

        stats["wrong_topics"].append(
            {
                "category": category,
                "topic": topic,
            }
        )

    return stats


# =========================================================
# 正答率
# =========================================================

def calculate_percentage(
    correct,
    total,
):
    """
    正答率を計算する。
    """

    if total == 0:
        return 0.0

    return round(
        correct / total * 100,
        1,
    )


# =========================================================
# 成績サマリー
# =========================================================

def get_exam_summary(stats):
    """
    学習成績を画面表示しやすい形に整理する。
    """

    overall = calculate_percentage(
        stats["correct_answers"],
        stats["total_questions"],
    )

    categories = []

    for (
        category,
        result,
    ) in stats["by_category"].items():

        percentage = (
            calculate_percentage(
                result["correct"],
                result["total"],
            )
        )

        categories.append(
            {
                "分野": category,
                "正答数": result["correct"],
                "問題数": result["total"],
                "正答率": percentage,
            }
        )

    categories.sort(
        key=lambda x: x["正答率"]
    )

    return {
        "overall_percentage": overall,
        "categories": categories,
        "wrong_topics": stats[
            "wrong_topics"
        ],
    }


# =========================================================
# 苦手分野判定
# =========================================================

def get_weak_categories(
    stats,
    threshold=70.0,
):
    """
    正答率が指定値未満の分野を抽出する。

    デフォルトでは70%未満。
    """

    weak = []

    for (
        category,
        result,
    ) in stats["by_category"].items():

        if result["total"] == 0:
            continue

        percentage = (
            calculate_percentage(
                result["correct"],
                result["total"],
            )
        )

        if percentage < threshold:

            weak.append(
                {
                    "分野": category,
                    "正答率": percentage,
                    "問題数": result[
                        "total"
                    ],
                }
            )

    weak.sort(
        key=lambda x: x["正答率"]
    )

    return weak


# =========================================================
# 間違い復習プロンプト
# =========================================================

def build_review_prompt(
    wrong_topics,
):
    """
    誤答したテーマを復習するための
    AIプロンプトを作成する。
    """

    if not wrong_topics:

        return """
現在、復習対象として登録された
誤答テーマはありません。
"""

    topic_lines = []

    for item in wrong_topics:

        topic_lines.append(
            f"- {item['category']}："
            f"{item['topic']}"
        )

    topics = "\n".join(
        topic_lines
    )

    return f"""
以下は学生がこれまでに
誤答したテーマです。

{topics}

この結果を踏まえて、

1. 苦手になっている知識領域
2. 混同している可能性がある内容
3. 最優先で復習する項目
4. 簡潔な復習
5. 類似問題
6. 少し条件を変えた応用問題

を作成してください。

問題は
「🤖 AI作成オリジナル問題」
であることを明示してください。
"""


