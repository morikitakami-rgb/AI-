import re


# =========================================================
# OT Practice Copilot
# 個人情報・匿名化チェック
# =========================================================


# ---------------------------------------------------------
# 個人情報として注意するキーワード
# ---------------------------------------------------------

SENSITIVE_KEYWORDS = [
    "氏名：",
    "氏名:",
    "名前：",
    "名前:",
    "住所：",
    "住所:",
    "電話番号",
    "携帯番号",
    "メールアドレス",
    "患者ID",
    "患者ＩＤ",
    "患者番号",
    "カルテ番号",
    "診察券番号",
    "職員番号",
    "社員番号",
    "学籍番号",
    "生年月日",
]


# ---------------------------------------------------------
# 個人情報の可能性があるパターン
# ---------------------------------------------------------

SENSITIVE_PATTERNS = {

    "メールアドレス": re.compile(
        r"\b[A-Za-z0-9._%+-]+@[A-Za-z0-9.-]+\.[A-Za-z]{2,}\b"
    ),

    "郵便番号": re.compile(
        r"〒?\s*\d{3}-?\d{4}"
    ),

    "電話番号": re.compile(
        r"(?<!\d)"
        r"(?:0\d{1,4}[-ー－]?\d{1,4}[-ー－]?\d{3,4})"
        r"(?!\d)"
    ),

    "年月日形式": re.compile(
        r"(?:19|20)\d{2}[年/\-.]"
        r"\d{1,2}[月/\-.]"
        r"\d{1,2}日?"
    ),
}


# =========================================================
# 個人情報候補を検出
# =========================================================

def detect_sensitive_information(text):
    """
    入力文中に個人情報の可能性がある表現が
    含まれていないか簡易的に確認する。

    戻り値：
    検出された項目名のリスト
    """

    if not text:
        return []

    detected = []


    # -----------------------------------------------------
    # キーワードチェック
    # -----------------------------------------------------

    for keyword in SENSITIVE_KEYWORDS:

        if keyword in text:

            detected.append(
                f"注意キーワード：{keyword}"
            )


    # -----------------------------------------------------
    # 正規表現チェック
    # -----------------------------------------------------

    for label, pattern in (
        SENSITIVE_PATTERNS.items()
    ):

        if pattern.search(text):

            detected.append(label)


    # -----------------------------------------------------
    # 重複削除
    # -----------------------------------------------------

    return list(
        dict.fromkeys(detected)
    )


# =========================================================
# 安全性チェック
# =========================================================

def has_sensitive_information(text):
    """
    個人情報の可能性がある表現が
    1つ以上検出された場合Trueを返す。
    """

    return bool(
        detect_sensitive_information(text)
    )


# =========================================================
# ユーザー向け警告文
# =========================================================

def get_privacy_warning(text):
    """
    検出内容に応じた警告メッセージを作成する。
    """

    detected = (
        detect_sensitive_information(text)
    )

    if not detected:
        return None

    items = "\n".join(
        f"・{item}"
        for item in detected
    )

    return f"""
個人を特定できる可能性のある情報が
含まれている可能性があります。

検出された項目：
{items}

氏名、正確な生年月日、住所、電話番号、
メールアドレス、患者ID、職員番号、
学籍番号、具体的な施設名・勤務先名などを削除し、
匿名化してから再入力してください。

※この機能は簡易チェックであり、
完全な匿名化を保証するものではありません。
""".strip()


